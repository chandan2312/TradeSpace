// TradeSpace Automated Background Maintenance & Memory Purge Engine.
// Runs scheduled cleanups every 1 hour to prevent VPS RAM/CPU exhaustion,
// stale temp accumulation, and database bloat.
import fs from "fs";
import path from "path";
import { exec } from "child_process";
import { pruneStaleTriggeredAlerts } from "./alert-engine.js";

const CLEANUP_INTERVAL_MS = 60 * 60 * 1000; // Every 1 hour
let isRunning = false;

function cleanOldTempFiles() {
  const tempDir = process.env.TEMP || process.env.TMP;
  if (!tempDir || !fs.existsSync(tempDir)) return 0;

  let cleaned = 0;
  const now = Date.now();
  const maxAgeMs = 6 * 60 * 60 * 1000; // 6 hours

  try {
    const files = fs.readdirSync(tempDir);
    for (const f of files) {
      // Target temporary files, logs, and crash dumps generated by browsers, node, or MT5
      if (f.endsWith(".tmp") || f.endsWith(".dmp") || f.startsWith("scoped_dir") || f.startsWith("chrome_")) {
        try {
          const filePath = path.join(tempDir, f);
          const stat = fs.statSync(filePath);
          if (now - stat.mtimeMs > maxAgeMs) {
            if (stat.isDirectory()) {
              fs.rmSync(filePath, { recursive: true, force: true });
            } else {
              fs.unlinkSync(filePath);
            }
            cleaned++;
          }
        } catch {
          // File might be in use by another active process; safely skip
        }
      }
    }
  } catch (err) {
    // Non-fatal if directory read fails
  }
  return cleaned;
}

export async function runMaintenance() {
  if (isRunning) return;
  isRunning = true;
  const start = Date.now();

  try {
    // 1. Prune stale triggered alerts from prior trading days
    const prunedAlerts = await pruneStaleTriggeredAlerts().catch(() => 0);

    // 2. Clean temporary files older than 6 hours
    const cleanedTemp = cleanOldTempFiles();

    // 3. Compact V8 memory heap
    if (typeof global.gc === "function") {
      try {
        global.gc();
      } catch {}
    }

    const elapsed = Date.now() - start;
    console.log(`[maintenance] automated 1-hour purge complete in ${elapsed}ms: ${prunedAlerts} stale alerts pruned, ${cleanedTemp} temp files cleaned, RAM compacted.`);
  } catch (err) {
    console.error("[maintenance] cleanup error:", err?.message || err);
  } finally {
    isRunning = false;
  }
}

export function startMaintenanceLoop() {
  // First run 30 seconds after server boot to allow initialization to finish
  setTimeout(() => {
    runMaintenance().catch(() => {});
  }, 30_000);

  // Subsequent recurring run every 1 hour
  setInterval(() => {
    runMaintenance().catch(() => {});
  }, CLEANUP_INTERVAL_MS);

  console.log(`[maintenance] automated hourly background maintenance engine active (interval: 1 hour)`);
}
